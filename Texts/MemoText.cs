ПОДСКАЗКИ ПО ТЮНИНГУ.
  0) Новая модель: сначала V100 ONLY. Затем SAFE V100+RTX. BALANCED и
   AGGRESSIVE включай только после стабильного прогона и с тем же
   набором уже открытых приложений. Не меняй GPU-нагрузку на лету.
  1) Для агента сначала 32k context. 64k имеет смысл только когда нужен:
   большой ctx отъедает KV/RS/scratch и может вытолкнуть веса на CPU.
  2) Q8, который физически не помещается в суммарную свободную VRAM,
   неизбежно получит CPU offload и может быть намного медленнее Q6/Q4.
  3) -b влияет в основном на prompt processing, -ub на физический кусок
   batch и scratch. Дефолт 2048/512. Для V100 полезно БЕНЧМАРКОМ
   проверить ubatch 64/128/256/512/1024 — универсального победителя нет.
  4) --cache-prompt включён сервером по умолчанию. --cache-reuse может
   заметно помочь агентам на повторяющихся длинных префиксах, но для
   ЧИСТОГО benchmark его лучше держать 0.
  5) --sse-ping-interval 10–15 с помогает не оставлять HTTP/SSE соединение
   совсем немым во время долгого prefill. Если агент имеет СВОЙ жёсткий
   timeout, его всё равно надо увеличивать в настройках агента.
  6) reasoning budget: 4–8k токенов в рутине, 16–32k в сложном коде;
   0 в ЭТОМ UI = не передавать флаг (runtime использует свой default).
  7) MTP может ускорить decode при хорошем acceptance, но расходует память.
   На пограничном Q8 сначала добейся стабильной работы БЕЗ MTP.
  8) Sampling-параметры (temp, penalties и т.д.) — это ДЕФОЛТЫ СЕРВЕРА:
   их можно переопределить в каждом запросе. Для чистого benchmark
   держи общий переключатель sampling выключенным.

TOOL-CALLS / АГЕНТНАЯ РАБОТА (--jinja):

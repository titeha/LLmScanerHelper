================= ПОЧЕМУ ТАК (памятка, чтобы не вспоминать месяц) ====

ЕДИНИЦЫ. Вся память считается в GiB (1024^3) — так же показывают
  nvidia-smi и llama.cpp. Значения VRAM бери из nvidia-smi; если на
  V100 включён ECC, nvidia-smi УЖЕ показывает уменьшенный итог —
  просто вводишь то, что видишь.

ЗАЩИТА VRAM. В AUTO-режиме резерв теперь НЕ участвует в нашей
  самодельной формуле слоёв. Он напрямую превращается в --fit-target:
  это целевой объём свободной VRAM, который llama.cpp старается
  оставить ПОСЛЕ загрузки модели. Для V100 без Windows достаточно
  небольшого технологического запаса (по умолчанию 0.50 GiB).
  Для RTX, на которой живёт WDDM/рабочий стол/браузеры/IDE, нужен
  отдельный большой запас: SAFE=3.00 GiB, BALANCED=2.50 GiB,
  AGGRESSIVE=2.00 GiB. Ниже 2 GiB этот UI намеренно не предлагает.

  ВАЖНО: --fit-target — НЕ аппаратный hard-cap. Runtime рассчитывает
  раскладку по свободной VRAM на момент загрузки. Если ПОСЛЕ загрузки
  открыть браузер, видео, игру, второй LLM или иное GPU-приложение,
  новый потребитель может съесть оставленный запас. Поэтому во время
  агентного прогона держим рабочее окружение стабильным: не открываем
  новые GPU-тяжёлые окна/приложения. Для новой/подозрительной модели
  сначала используй профиль V100 ONLY — это настоящая изоляция RTX.

ВАЖНО ДЛЯ НОВЫХ QWEN/ГИБРИДНЫХ АРХИТЕКТУР. Формула "веса + обычный
  KV на каждый слой" уже НЕ является точной: recurrent/linear-attn
  слои имеют отдельный state (RS cache), MTP создаёт дополнительный
  speculative context, а compute/scratch зависит от -b/-ub и FA.
  Поэтому точную раскладку по VRAM в AUTO-режиме делает САМ llama.cpp
  через --fit. Этот инструмент больше не притворяется умнее runtime.

KV-КЭШ. K и V задаются раздельно (--cache-type-k и -v). q8_0 —
  хороший рабочий компромисс. q4_0 экономит память, но на длинном
  контексте может сильнее влиять на качество. Если включён Flash
  Attention и KV квантован, конкретная сборка llama.cpp должна иметь
  нужные CUDA FA kernels; при подозрительно низкой скорости проверь
  лог и сравни -fa auto/on, а кастомную сборку делай с
  GGML_CUDA_FA_ALL_QUANTS=ON.

ПОВЕДЕНИЕ llama.cpp.
  AUTO: НЕ задаём точный -ngl и НЕ задаём --tensor-split. Передаём
  --fit on + отдельный --fit-target для устройств В ТОМ ЖЕ ПОРЯДКЕ,
  что и --device. Runtime сам выбирает раскладку по реально свободной
  VRAM, включая KV/RS/compute/speculative context.
  MANUAL: --fit off, -ngl задаётся явно, а --tensor-split X,Y — это
  ПРОПОРЦИИ распределения offload, НЕ точное количество слоёв.
  split-mode layer — правильный дефолт для V100 + RTX на разных PCIe;
  tensor — экспериментальный и требовательнее к меж-GPU связи.

  MTP: модели могут хранить дополнительный блок как blk.N при
  N == block_count, а тензоры часто содержат nextn/mtp. Программа их
  детектирует, но размер MTP используется только для информации.
  Реальный расход памяти MTP больше размера его тензоров, поэтому в
  AUTO оставляй нормальный --fit-target. Дефолты llama.cpp для MTP:
  draft max=3, draft min=0. min никогда не должен быть > max.
  WPF-версия: для Q8-квантов переключатель MTP отключён — издатель
  (unsloth) заявляет, что MTP на Q8_0 недоступен.

  reasoning детектим по чат-шаблону (enable_thinking/reasoning) и тегам.
  Имена флагов reasoning гуляют между билдами — имя флага бюджета
  лежит ОДНОЙ константой ReasoningBudgetFlag, правится в 1 месте.


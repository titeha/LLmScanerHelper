  запоминается в профиле модели и авто-детектом не сбрасывается.
  • Ограничения эвристики: шаблон может уметь tools, а модель — не уметь
  ими пользоваться (не обучена), и наоборот. Спорные случаи проверяй
  тестовым запросом с tools или карточкой модели на HF.

